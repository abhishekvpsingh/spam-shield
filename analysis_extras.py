"""Extra numbers cited in the slides / summary / error analysis, so every figure is reproducible.

Usage:  python analysis_extras.py      ->  results/extras.md
"""
import math

import numpy as np

from run_experiments import load_data, split, pick_threshold, TARGET_FPR
from spamshield.nb import NaiveBayes, tokenize

df, n_raw = load_data()  # Cleaned message table and original row count.
train, dev, test = split(df)  # Use the same 70/15/15 split as the experiments.
nb = NaiveBayes().fit(train.text, train.label)  # Train the custom Naive Bayes model.
out = ["# Extra analysis (generated by analysis_extras.py)\n"]  # Collect Markdown report lines.


def wilson(k, n, z=1.96):
    """95% Wilson score interval for a proportion k/n."""
    p = k / n  # Observed rate, e.g. 5 / 678.
    d = 1 + z * z / n  # Wilson adjustment for sample size.
    c = p + z * z / (2 * n)  # Adjusted center before division by d.
    r = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))  # Uncertainty width before division by d.
    return (c - r) / d, (c + r) / d  # Lower and upper rate bounds, e.g. (0.003, 0.017).


# 1) Is the gap between models bigger than noise? (95% intervals; overlap = not conclusive)
out.append("## 1. Uncertainty on the headline numbers (test set: 96 spam, 678 ham)\n")
out.append("| quantity | count | rate | 95% interval |\n|---|---|---|---|")
for name, k, n in [("NB (thr 0.5) false-positive rate", 5, 678), ("NB (thr 0.5) spam recall", 85, 96),
                   ("LogReg tuned false-positive rate", 1, 678), ("LogReg tuned spam recall", 90, 96)]:
    lo, hi = wilson(k, n)  # Calculate bounds for the hard-coded result counts above.
    out.append(f"| {name} | {k}/{n} | {k / n:.4f} | [{lo:.4f}, {hi:.4f}] |")  # Table row with count, rate, and interval.
out.append("\nThe NB and LogReg intervals overlap on both quantities, so the test set cannot prove one model is "
           "better. One extra false positive moves the FPR by about 0.15 points.\n")

# 2) Naive Bayes probability overconfidence
pt = np.array([nb.spam_probability(t) for t in test.text])  # One spam probability per test message.
pdv = np.array([nb.spam_probability(t) for t in dev.text])  # One spam probability per dev message.
extreme = np.mean((pt < 0.01) | (pt > 0.99))  # Fraction of test scores near 0 or 1.
middle = np.mean((pt > 0.1) & (pt < 0.9))  # Fraction of test scores between 0.1 and 0.9.
out.append("## 2. Naive Bayes probabilities are extreme\n")
out.append(f"On the test set, {extreme:.1%} of messages get P(spam) below 0.01 or above 0.99; only {middle:.1%} fall "
           "between 0.1 and 0.9. A threshold has little room to trade precision for recall, and tuning it is unstable.\n")

# 3) Did the dev-tuned threshold transfer?
thr = pick_threshold(pdv, dev.label, TARGET_FPR)  # Choose a cutoff using dev messages only.
yd, yt = dev.label.values, test.label.values  # Label arrays used to select ham or spam scores.
out.append("## 3. Did the dev-tuned NB threshold transfer to test?\n")
out.append(f"Threshold chosen on dev for FPR <= {TARGET_FPR:.1%}: {thr:.4f}.\n")
out.append("| split | ham FPR | spam recall |\n|---|---|---|")
out.append(f"| dev | {(pdv[yd == 'ham'] >= thr).mean():.4f} | {(pdv[yd == 'spam'] >= thr).mean():.3f} |")
out.append(f"| test | {(pt[yt == 'ham'] >= thr).mean():.4f} | {(pt[yt == 'spam'] >= thr).mean():.3f} |\n")
out.append("The target was met on dev but exceeded on test, so the tuned threshold did not generalise.\n")


# 4) Word evidence used in the error analysis: in how many training messages does a word appear?
def msg_counts(w):
    s = sum(w in set(tokenize(t)) for t in train[train.label == "spam"].text)  # Count spam messages containing this word once or more.
    h = sum(w in set(tokenize(t)) for t in train[train.label == "ham"].text)  # Count ham messages containing this word once or more.
    return s, h  # Two message counts, e.g. (12, 3).


out.append("## 4. Word evidence (number of TRAINING messages containing the word)\n")
out.append("| word | in spam | in ham | in vocabulary? |\n|---|---|---|---|")
for w in ["nokia", "phone", "unlimited", "texts", "minutes", "lovly", "free", "call", "i", "me", "my", "18",
          "£250", "£800", "0870", "bailiff", "l8er", "toll", "pay", "confirm"]:
    s, h = msg_counts(w)  # Get training-message counts for this word.
    out.append(f"| {w} | {s} | {h} | {'yes' if w in nb.vocab else 'NO (ignored)'} |")  # Table row with counts and vocabulary status.
out.append(f"\nAverage tokens per training message: spam "
           f"{np.mean([len(tokenize(t)) for t in train[train.label == 'spam'].text]):.1f}, "
           f"ham {np.mean([len(tokenize(t)) for t in train[train.label == 'ham'].text]):.1f}.\n")

open("results/extras.md", "w").write("\n".join(out) + "\n")  # Save the extra analysis as a Markdown report.
print("\n".join(out))  # Print the same report in the terminal.
